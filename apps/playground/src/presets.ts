import { BASE, FONTS, VARS, type Colors, type Theme } from "./tokens.ts";

export interface Preset {
  name: string;
  rationale: string;
  recommended?: boolean;
  theme: Theme;
}

const option = (key: string, label: string) => {
  const control = VARS.find((v) => v.key === key);
  const found = control?.kind === "select" && control.options.find((o) => o.label === label);
  if (!found) throw new Error(`No option ${label} for ${key}`);
  return found.value;
};
const font = (label: string) => FONTS.find((f) => f.label === label)!.value;

function preset(
  name: string,
  rationale: string,
  over: { light?: Colors; dark?: Colors; vars?: Record<string, string> },
  recommended?: boolean,
): Preset {
  return {
    name,
    rationale,
    recommended,
    theme: {
      light: { ...BASE.light, ...over.light },
      dark: { ...BASE.dark, ...over.dark },
      vars: { ...BASE.vars, ...over.vars },
    },
  };
}

